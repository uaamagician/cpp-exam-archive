//
//	 假設：美式咖啡售價 60 元、抹茶拿鐵售價是美式的 1.5 倍
//	       加奶每杯多 15 元
//
//   每次依序詢問要購買的美式杯數、抹茶拿鐵杯數、加奶杯數
//   總價 = 美式與抹茶拿鐵的飲料錢 + 加奶的錢
//   總杯數只算美式與抹茶拿鐵（加奶不算杯數）
//
//	 需求一：
//			 當總價超過(含) 1000 時售價打 9 折
// 			 輸出應付的原價與打折後的總價
//   需求 2 :
//			詢問要購買的杯數（同上）
//			當總杯數超過(含) 15 杯時售價打 9 折，且美式與抹茶拿鐵都買 3 送 1
//          沒有滿足打折條件時，美式與抹茶拿鐵都是買 5 送 1
//			輸出應付的原價與打折後的總價以及各應給的杯數
//
//	 計分方式
//		1. 完成需求 1 , 1 分
//      2. 各品項售價以 #define 宣告為常數符號，且完成需求1的輸出， 1 分
//		3. 完成需求 2 , 2 分
//
//   提示：需使用 if...else，將兩個需求的程式碼各複製一份到對應的 printf 函式後面即可連續輸入兩次
//		   需求 1 兩次輸入分別為 6 4 3 以及 10 6 4
//		   需求 2 兩次輸入分別為 7 5 2 以及 10 8 4
//         輸出結果與下面的參考輸出相同即可。
// ---------------------------------------------------------------------------------------------
//   以下的輸出為本題輸出參考
//	------------需求 1 ------------
// 	依序輸入美式、抹茶拿鐵、加奶的杯數 : 6 4 3
//  未達打折條件，總價為: 765
//	依序輸入美式、抹茶拿鐵、加奶的杯數 : 10 6 4
//	總價為: 1200 打折後是 1080
//
// 	------------需求 2 ------------
// 	依序輸入美式、抹茶拿鐵、加奶的杯數 : 7 5 2
//  未達打折條件，總價為: 900
//	美式原購買:  7 杯, 抹茶拿鐵原購買:  5 杯
//	美式應製作:  8 杯, 抹茶拿鐵應製作:  6 杯
//
// 	依序輸入美式、抹茶拿鐵、加奶的杯數 : 10 8 4
//  總價為: 1380 打折後是 1242
//	美式原購買: 10 杯, 抹茶拿鐵原購買:  8 杯
//	美式應製作: 13 杯, 抹茶拿鐵應製作: 10 杯
//

