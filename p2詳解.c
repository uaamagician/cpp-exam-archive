// 1. 考點：#define 常數符號、if...else、整數運算、整數除法的捨去
// 2. 常數寫法：#define AMERICANO 60（不加分號、不加 =）。沒用常數符號，這題的分數會被扣
// 3. 抹茶拿鐵是美式的 1.5 倍：#define LATTE (AMERICANO * 3 / 2)
//    - 一定要用整數運算（先乘 3 再除 2），60 * 3 / 2 = 90；不要寫 1.5，題目要求全部用 int
//    - 整個式子要用括號包起來，這樣 la * LATTE 才會展開成 la * (AMERICANO * 3 / 2)
// 4. 整數折扣：9 折 = tp * 90 / 100，先乘再除；不要寫 tp * 0.9（浮點數轉 int 可能少 1 元）
// 5. 買 m 送 1：送的杯數 = n / m（整數除法自動捨去），實際製作杯數 = n + n / m
//    例如 10 杯買 3 送 1：10 / 3 = 3，實際製作 13 杯；7 杯買 5 送 1：7 / 5 = 1，實際製作 8 杯
// 6. 兩次輸入：把需求的程式碼整段複製一份，中間用 rewind(stdin) 清掉輸入緩衝區
// 7. 手算驗證：
//      需求 1：6*60 + 4*90 + 3*15 = 360 + 360 + 45 = 765 < 1000 -> 不打折
//              10*60 + 6*90 + 4*15 = 600 + 540 + 60 = 1200 >= 1000 -> 1200 * 90 / 100 = 1080
//      需求 2：7 + 5 = 12 杯 < 15 -> 不打折，總價 420 + 450 + 30 = 900，美式 7 + 7/5 = 8，拿鐵 5 + 5/5 = 6
//              10 + 8 = 18 杯 >= 15 -> 打 9 折，總價 600 + 720 + 60 = 1380，1380 * 90 / 100 = 1242
//              美式 10 + 10/3 = 13，拿鐵 8 + 8/3 = 10
// 8. 易錯點：加奶不算杯數（總杯數只用 am + la）；「超過(含)」是 >=，「超過」是 >
