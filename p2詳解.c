#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>

#define AMERICANO 60
#define LATTE (AMERICANO * 3 / 2)
#define MILK 15

int main(void)
{
	int am, la, mk, tp, tc;
	int tp2, am2, la2;

	printf("------------  需求 1 ------------\n");
	printf("依序輸入美式、抹茶拿鐵、加奶的杯數 : "); scanf("%d%d%d", &am, &la, &mk);

	tp = am * AMERICANO + la * LATTE + mk * MILK;

	if (tp >= 1000) {
		tp2 = tp * 90 / 100;
		printf("總價為: %d 打折後是 %d \n", tp, tp2);
	}
	else {
		printf("未達打折條件，總價為: %d \n", tp);
	}
	rewind(stdin);
	printf("依序輸入美式、抹茶拿鐵、加奶的杯數 : "); scanf("%d%d%d", &am, &la, &mk);

	tp = am * AMERICANO + la * LATTE + mk * MILK;

	if (tp >= 1000) {
		tp2 = tp * 90 / 100;
		printf("總價為: %d 打折後是 %d \n", tp, tp2);
	}
	else {
		printf("未達打折條件，總價為: %d \n", tp);
	}

	printf("\n------------  需求 2 ------------\n");
	printf("依序輸入美式、抹茶拿鐵、加奶的杯數 : "); scanf("%d%d%d", &am, &la, &mk);

	tp = am * AMERICANO + la * LATTE + mk * MILK;
	tc = am + la;

	if (tc >= 15) {
		tp2 = tp * 90 / 100;
		am2 = am + am / 3;
		la2 = la + la / 3;
		printf("總價為: %d 打折後是 %d \n", tp, tp2);
	}
	else {
		am2 = am + am / 5;
		la2 = la + la / 5;
		printf("未達打折條件，總價為: %d \n", tp);
	}
	printf("美式原購買: %2d 杯, 抹茶拿鐵原購買: %2d 杯\n", am, la);
	printf("美式應製作: %2d 杯, 抹茶拿鐵應製作: %2d 杯\n\n", am2, la2);

	rewind(stdin);
	printf("依序輸入美式、抹茶拿鐵、加奶的杯數 : "); scanf("%d%d%d", &am, &la, &mk);

	tp = am * AMERICANO + la * LATTE + mk * MILK;
	tc = am + la;

	if (tc >= 15) {
		tp2 = tp * 90 / 100;
		am2 = am + am / 3;
		la2 = la + la / 3;
		printf("總價為: %d 打折後是 %d \n", tp, tp2);
	}
	else {
		am2 = am + am / 5;
		la2 = la + la / 5;
		printf("未達打折條件，總價為: %d \n", tp);
	}
	printf("美式原購買: %2d 杯, 抹茶拿鐵原購買: %2d 杯\n", am, la);
	printf("美式應製作: %2d 杯, 抹茶拿鐵應製作: %2d 杯\n\n", am2, la2);

	system("pause"); return(0);
}

