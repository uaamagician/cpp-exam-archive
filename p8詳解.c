/* =================================== 詳解 ===================================
1. 考點：二維概念的一維陣列索引、位元運算（<<= 與 |=）、while 巢狀迴圈、字元就是整數
2. 題目與程式碼的兩個問題（題目沒有改，照原樣）：
   (1) while (j < 6) 那段多了一個 `}`，編譯會出錯，唯一的處理是刪掉它（刪掉後才能執行）
   (2) Array 的第 5 組是 0,1,1,0,0,0,1,1（= 'c'），但題目上方的二進位字串第 5 組是 01110011（= 's'）
       兩邊不一致，所以程式實際輸出是 finich，不是 finish
       （如果要得到 finish，要把 Array 第 5 組改成 0,1,1,1,0,0,1,1）
3. 每八個 0 或 1 是一個字元的 ASCII 碼，共 6 個字元：
   - 外層 j 是第幾個字元（0 到 5），內層 i 是這個字元的第幾個位元（0 到 7）
   - 第 j 組第 i 個位元在陣列裡的位置是 j * 8 + i
4. 把八個位元組成一個數：
   - Word[j] <<= 1：整個數往左移一位（相當於乘 2），為下一個位元騰出最右邊的位置
   - Word[j] |= Array[j*8+i]：把這一個位元（0 或 1）放進最右邊
   例：01100110 一個一個放進去，結果是 0b01100110 = 102 = 'f'
5. 每個字元算完後，i 要歸零，才能算下一組
6. Word 陣列大小 10 且一開始全部是 0，所以字串自然以 '\0' 結尾，printf("%s") 才不會印到後面亂碼
7. 手算驗證（二進位轉十進位再對照 ASCII）：
   01100110 = 102 = 'f'    01101001 = 105 = 'i'    01101110 = 110 = 'n'
   01101001 = 105 = 'i'    01110011 = 115 = 's'    01101000 = 104 = 'h'
   照題目的二進位字串會是 finish；但照程式裡的 Array，第 5 組是 99 = 'c'，實際輸出 finich
8. 易錯點：i 忘了歸零；Word[j] 沒有先設成 0（全域陣列預設就是 0，區域陣列要自己設）；
   把 Array[j*8+i] 寫成 Array[i]（每組都拿到第一組的位元）
*/
