#include <stdio.h>
#include <stdlib.h>

void printspace(int x) {
    while (x > 0) {
        printf(" ");
        x--;
    }
}

void printstar(int x) {
    while (x > 0) {
        printf("*");
        x--;
    }
}

int main() {
    int i, s, k;

    printf("//--- 第一小題 ---//\n");
    i = 1;
    while (i <= 7) {
        printspace(8 - i);
        printstar(2 * i - 1);
        printf("\n");
        i++;
    }

    printf("//--- 第二小題 ---//\n");
    s = 1;
    while (s <= 5) {
        k = s;
        while (k <= s + 4) {
            printspace(8 - (k + 1) / 2);
            printstar(k);
            printf("\n");
            k += 2;
        }
        s += 2;
    }
    printspace(6);
    printstar(3);
    printf("\n");

    system("pause");
    return 0;
}

