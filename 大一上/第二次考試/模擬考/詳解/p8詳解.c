// 程式設計一 第二次上機寫題，第八題 (3+3分)
//
//   需求一：
//      輸入一個正整數 n，輸出 n 的二進位
//      (不斷用 % 2 取餘數、/ 2 往下除，餘數要先存進陣列，最後倒著輸出)
//   需求二：
//      輸入一個二進位字串，先檢查是不是只由 0 和 1 組成
//      不是的話輸出「不是二進位字串」；是的話，算出它的十進位並輸出
//
//   計分方式
//      1. 完成需求一，3 分
//      2. 完成需求二，3 分
//
//   提示：1. 餘數是從最低位開始出來的，所以輸出時要由最後存進去的位置往回印
//         2. 二進位字串轉十進位：由左到右，每讀一個字元，v = v * 2 + (這個字元的數字)
//         3. 字元 '0'、'1' 轉成數字 0、1，使用 s[i] - '0'
//         4. 檢查字串使用旗標 flag，起始為 1，發現不是 0 也不是 1 的字元就改成 0
//         輸出結果與下面的參考輸出相同即可。
//   變數要求
//      int 變數 n 放輸入的數，cnt 放存進 bits 的個數，v 放十進位結果，flag 是旗標
//      cnt、v 的起始值是 0，flag 的起始值是 1
//      int 陣列 bits，32 個元素；char 陣列 s，33 個元素
//      迴圈用的變數請自己宣告，名稱使用 i
//   流程提示
//      需求一 (n = 13)：13 % 2 = 1，n 變 6；6 % 2 = 0，n 變 3；3 % 2 = 1，n 變 1；1 % 2 = 1，n 變 0 結束
//                        bits 依序是 1 0 1 1，cnt = 4，從 bits[3] 倒著印到 bits[0]，得 1101
//      需求二 (1011)：v 起始 0 -> 0*2+1 = 1 -> 1*2+0 = 2 -> 2*2+1 = 5 -> 5*2+1 = 11
// ---------------------------------------------------------------------------------------------
//   以下的輸出為本題輸出參考
//   輸入正整數 n: 13
//   二進位: 1101
//   輸入二進位字串: 1011
//   十進位: 11
//
//   輸入正整數 n: 1
//   二進位: 1
//   輸入二進位字串: 10201
//   不是二進位字串

