#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>

int main(void)
{
	int n, cnt = 0, i, v = 0, flag = 1;
	int bits[32];
	char s[33];

	printf("輸入正整數 n: "); scanf("%d", &n);
	while (n > 0) {
		bits[cnt] = n % 2;
		cnt++;
		n = n / 2;
	}
	printf("二進位: ");
	for (i = cnt - 1; i >= 0; i--) {
		printf("%d", bits[i]);
	}
	printf("\n");

	printf("輸入二進位字串: "); scanf("%s", s);
	for (i = 0; s[i] != '\0'; i++) {
		if (s[i] != '0' && s[i] != '1') {
			flag = 0;
		}
	}

	if (flag == 0) {
		printf("不是二進位字串\n");
	}
	else {
		for (i = 0; s[i] != '\0'; i++) {
			v = v * 2 + (s[i] - '0');
		}
		printf("十進位: %d\n", v);
	}

	system("pause"); return(0);
}

#endif

// =================================== 詳解 ===================================
// 1. 考點：while 與 % / 的進位轉換、一維陣列、倒序輸出、字元轉數字、旗標 flag
// 2. 需求一：n % 2 是最低位，先存進 bits，n 再除以 2，一直到 n 變成 0。餘數是由低位到高位出來的，所以最後要從 cnt - 1 倒著印
// 3. 需求二：flag 先假設合法，只要有一個字元不是 '0' 也不是 '1' 就改成 0；合法時由左到右 v = v * 2 + (s[i] - '0')
// 4. 手算驗證：
//      13：13%2=1 (n=6)，6%2=0 (n=3)，3%2=1 (n=1)，1%2=1 (n=0)，bits = 1 0 1 1，倒著印 1101
//      1011：0*2+1=1，1*2+0=2，2*2+1=5，5*2+1=11
// 5. 易錯點：需求一的順序印反了 (從 0 印到 cnt - 1)；字元轉數字漏了 - '0'，v 會加上 48 或 49；檢查時兩個條件要用 &&，寫成 || 會永遠為真
