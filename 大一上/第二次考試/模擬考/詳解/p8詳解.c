#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>

int main(void)
{
	int n, cnt = 0, i, v = 0, flag = 1;
	int bits[32];
	char s[33];

	printf("輸入正整數 n: "); scanf("%d", &n);
	while (n > 0) {
		bits[cnt] = n % 2;
		cnt++;
		n = n / 2;
	}
	printf("二進位: ");
	for (i = cnt - 1; i >= 0; i--) {
		printf("%d", bits[i]);
	}
	printf("\n");

	printf("輸入二進位字串: "); scanf("%s", s);
	for (i = 0; s[i] != '\0'; i++) {
		if (s[i] != '0' && s[i] != '1') {
			flag = 0;
		}
	}

	if (flag == 0) {
		printf("不是二進位字串\n");
	}
	else {
		for (i = 0; s[i] != '\0'; i++) {
			v = v * 2 + (s[i] - '0');
		}
		printf("十進位: %d\n", v);
	}

	system("pause"); return(0);
}

#endif

// =================================== 詳解 ===================================
// 一、這題在考什麼
//    while 與 % / 的進位轉換、一維陣列、倒序輸出、字元轉數字、旗標 flag
// 二、解題思路
//    需求一 (十進位轉二進位)：每次用 % 2 取出最低位，再把 n 除以 2，一直做到 n 變 0。
//            餘數是從最低位 (最右邊) 先出來的，但輸出要從最高位印，所以要先存進陣列，最後倒著印。
//    需求二 (二進位字串轉十進位)：先檢查每個字元是不是 0 或 1，用 flag 記錄。
//            合法時由左到右讀：每讀一位，把目前的值乘 2，再加上這一位。
// 三、程式逐段說明
//    bits[cnt] = n % 2; cnt++; n = n / 2;     取最低位存進陣列，位數 cnt 加 1，n 往下除
//    for (i = cnt - 1; i >= 0; i--)           最後存進去的是最高位，所以從 cnt - 1 倒著印
//    if (s[i] != '0' && s[i] != '1')          兩個條件都不是才是非法字元，要用 &&，用 || 會永遠成立
//    v = v * 2 + (s[i] - '0');                乘 2 相當於全部左移一位，再加上新的一位；s[i] - '0' 把字元變成數字 0 或 1
// 四、手算追蹤
//    需求一 (n = 13)：
//         n     n % 2    存進      n / 2
//         13    1        bits[0]   6
//         6     0        bits[1]   3
//         3     1        bits[2]   1
//         1     1        bits[3]   0     結束，cnt = 4
//       bits = 1 0 1 1，從 bits[3] 倒著印到 bits[0]，得 1101
//    需求二 (1011)：
//         讀到    v 的計算          v
//         1       0 * 2 + 1         1
//         0       1 * 2 + 0         2
//         1       2 * 2 + 1         5
//         1       5 * 2 + 1         11
//       輸出 11；若輸入 10201，讀到 2 時 flag 變 0，印出不是二進位字串
// 五、易錯點
//    1. 需求一的順序印反了 (從 0 印到 cnt - 1，印出來是 1011，變成反的)
//    2. 字元轉數字漏了 - '0'，v 會加上 48 或 49
//    3. 檢查字元的條件寫成 ||，永遠為真，所有字串都被判成不合法
//    4. n 是 0 時 while 不執行，什麼都印不出來 (題目保證 n 是正整數，所以這題不用處理)
// 六、講課提醒
//    可以問同學：1011 為什麼是 11？(8 + 0 + 2 + 1)，v * 2 + 新的一位 這個方法為什麼會成立？(每多讀一位，前面所有位的權重都乘 2)
