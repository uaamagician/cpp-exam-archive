#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>

int isP(int n)
{
	int k = 2;

	if (n < 2) {
		return 0;
	}
	while (k * k <= n) {
		if (n % k == 0) {
			return 0;
		}
		k++;
	}
	return 1;
}

int main(void)
{
	int n, k, fac = 0, a, b, i, cnt = 0;

	printf("輸入 n: "); scanf("%d", &n);
	k = 1;
	while (k * k <= n) {
		if (n % k == 0) {
			if (k == n / k) {
				printf("%4d ", k);
				fac = fac + 1;
			}
			else {
				printf("%4d %4d ", k, n / k);
				fac = fac + 2;
			}
		}
		k++;
	}
	printf("\n共 %d 個因數\n", fac);

	printf("輸入範圍 a b: "); scanf("%d %d", &a, &b);
	for (i = a; i <= b; i++) {
		if (isP(i)) {
			printf("%4d", i);
			cnt++;
			if (cnt % 5 == 0) {
				printf("\n");
			}
		}
	}
	if (cnt % 5 != 0) {
		printf("\n");
	}
	printf("共 %d 個質數\n", cnt);

	system("pause"); return(0);
}

