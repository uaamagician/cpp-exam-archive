// 程式設計一 第二次上機寫題，第二題 (2+2分)
//
//   需求一：
//      輸入月份 (1~12)，用 switch 印出季節
//      3、4、5 月為春季，6、7、8 月為夏季，9、10、11 月為秋季，12、1、2 月為冬季
//      輸入其他數字則印出「月份錯誤」
//   需求二：
//      輸入一個算式「整數 運算符號 整數」，運算符號是 + - * / 其中一個，用 switch 算出結果
//      除法請印到小數點後 2 位，除數為 0 時印出「除數不能為 0」
//      運算符號不是這四個時印出「不支援的運算符號」
//
//   計分方式
//      1. 完成需求一，2 分
//      2. 完成需求二，2 分
//
//   提示：多個 case 共用同一段程式時，把 case 疊在一起，最後再寫一個 break
//         scanf 讀運算符號時，%c 前面要留一個空白："%d %c %d"
//         輸出結果與下面的參考輸出相同即可。
//   變數要求
//      int 變數 m 放月份，a、b 放算式的兩個整數
//      char 變數 op 放運算符號
// ---------------------------------------------------------------------------------------------
//   以下的輸出為本題輸出參考
//   輸入月份(1~12): 4
//   春季
//   輸入算式(例如 12 / 5): 12 / 5
//   12 / 5 = 2.40
//
//   輸入月份(1~12): 13
//   月份錯誤
//   輸入算式(例如 12 / 5): 8 / 0
//   除數不能為 0

#define P2
#ifdef P2

#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>

int main(void)
{
	int m, a, b;
	char op;

	printf("輸入月份(1~12): "); scanf("%d", &m);
	switch (m) {
	case 12: case 1: case 2:
		printf("冬季\n");
		break;
	case 3: case 4: case 5:
		printf("春季\n");
		break;
	case 6: case 7: case 8:
		printf("夏季\n");
		break;
	case 9: case 10: case 11:
		printf("秋季\n");
		break;
	default:
		printf("月份錯誤\n");
	}

	printf("輸入算式(例如 12 / 5): "); scanf("%d %c %d", &a, &op, &b);
	switch (op) {
	case '+':
		printf("%d + %d = %d\n", a, b, a + b);
		break;
	case '-':
		printf("%d - %d = %d\n", a, b, a - b);
		break;
	case '*':
		printf("%d * %d = %d\n", a, b, a * b);
		break;
	case '/':
		if (b == 0) {
			printf("除數不能為 0\n");
		}
		else {
			printf("%d / %d = %.2f\n", a, b, (float)a / b);
		}
		break;
	default:
		printf("不支援的運算符號\n");
	}

	system("pause"); return(0);
}

#endif

// =================================== 詳解 ===================================
// 一、這題在考什麼
//    switch、case 疊在一起共用、字元當 case、整數除法與型別轉換
// 二、解題思路
//    需求一：月份是整數，直接 switch (m)。12、1、2 都是冬季，所以三個 case 疊在一起，共用同一個 printf 和 break。
//            不在 1 到 12 的數字都走 default。
//    需求二：算式有三個東西，整數、符號、整數，用 scanf("%d %c %d") 一次讀進來。
//            再用 switch (op) 判斷是哪一種運算。除法要特別處理除數 0，還要印到小數點後 2 位。
// 三、程式逐段說明
//    case 12: case 1: case 2:             三個標籤指向同一段程式，進來任何一個都會執行下面的 printf
//    break;                               印完要跳出 switch，沒有 break 會繼續往下執行下一個 case
//    scanf("%d %c %d", ...)               %c 前面的空白很重要：它會略過空白，不然 %c 會讀到空白字元
//    case '/': if (b == 0) ...            除法先檢查除數，不能除以 0
//    (float)a / b                         先把 a 轉成 float 再除，12 / 5 才會是 2.4；寫 a / b 兩邊都是 int，會變 2
// 四、手算追蹤
//    輸入月份 4：對到 case 4，印春季，遇到 break 跳出
//    輸入月份 12：對到 case 12，後面接著 case 1、case 2 一起共用，印冬季
//    輸入月份 13：沒有任何 case 符合，走 default，印月份錯誤
//    算式 12 / 5：op 是 '/'，b 不是 0，(float)12 / 5 = 2.4，%.2f 印成 2.40
//    算式 8 / 0：op 是 '/'，b 是 0，印除數不能為 0
// 五、易錯點
//    1. 每個 case 結尾漏掉 break，會一路往下執行
//    2. 寫成 (float)(a / b)，括號位置錯，先做了整數除法，結果是 2.00
//    3. case 後面只能放常數，不能放變數或範圍 (case m > 5 是錯的)
//    4. scanf 的 %c 前面沒有空白，會把空白當成運算符號
// 六、講課提醒
//    可以問同學：如果把 case 3 的 break 拿掉，輸入 3 會印什麼？(印春季，然後掉到下一個 case 繼續印)
