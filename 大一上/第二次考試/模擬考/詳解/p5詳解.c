// 程式設計一 第二次上機寫題，第五題 (4分)
//
//   輸入一段文字，以 # 代表結束，統計：
//      1. 數字 0 到 9 各出現幾次 (只輸出有出現的數字)
//      2. 母音 a e i o u 各出現幾次 (大小寫視為相同)
//   請使用兩個一維陣列存放次數
//
//   提示：1. 用 getchar() 一次讀一個字元，直到讀到 #
//         2. 數字字元 '0' 到 '9'，用 ch - '0' 轉成 0 到 9 當作陣列的索引
//         3. 母音使用 switch，大小寫的 case 疊在一起共用
//         4. 陣列要先歸零：int digit[10] = { 0 };
//         輸出結果與下面的參考輸出相同即可。
//   變數要求
//      int 陣列 digit，10 個元素，放數字 0 到 9 的次數，起始值都是 0
//      int 陣列 vowel，5 個元素，依序放 a e i o u 的次數，起始值都是 0
//      char 變數 ch 放讀到的字元
//      迴圈用的變數請自己宣告，名稱使用 i
//   流程提示
//      while 每讀一個字元，只會走下面三條路的其中一條
//         (1) 是數字  -> digit[ch - '0'] 加 1       (用 if 判斷範圍)
//         (2) 是母音  -> 對應的 vowel 加 1           (用 switch，大小寫疊在一起)
//         (3) 其他字元 -> 什麼都不做                 (switch 沒有符合的 case 就會略過)
//      最後兩個陣列各自用輸出的方式印出來
// ---------------------------------------------------------------------------------------------
//   以下的輸出為本題輸出參考
//   輸入一段文字,以 # 結束:
//   I love 2025 apples, 11 eggs#
//   數字 0 出現 1 次
//   數字 1 出現 2 次
//   數字 2 出現 2 次
//   數字 5 出現 1 次
//   a:1 e:3 i:1 o:1 u:0

#define P5
#ifdef P5

#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>

int main(void)
{
	int digit[10] = { 0 };
	int vowel[5] = { 0 };
	int i;
	char ch;

	printf("輸入一段文字,以 # 結束:\n");
	while ((ch = getchar()) != '#') {
		if (ch >= '0' && ch <= '9') {
			digit[ch - '0']++;
		}
		else {
			switch (ch) {
			case 'a': case 'A':
				vowel[0]++;
				break;
			case 'e': case 'E':
				vowel[1]++;
				break;
			case 'i': case 'I':
				vowel[2]++;
				break;
			case 'o': case 'O':
				vowel[3]++;
				break;
			case 'u': case 'U':
				vowel[4]++;
				break;
			}
		}
	}

	for (i = 0; i < 10; i++) {
		if (digit[i] != 0) {
			printf("數字 %d 出現 %d 次\n", i, digit[i]);
		}
	}
	printf("a:%d e:%d i:%d o:%d u:%d\n", vowel[0], vowel[1], vowel[2], vowel[3], vowel[4]);

	system("pause"); return(0);
}

#endif

// =================================== 詳解 ===================================
// 一、這題在考什麼
//    getchar 逐字元讀取、一維陣列計數、字元運算 ch - '0'、switch 疊 case
// 二、解題思路
//    用 while 每次讀一個字元，直到讀到 #。每個字元只會有三種情況，彼此互斥：
//       (1) 是數字字元 -> 對應的 digit 加 1
//       (2) 是母音     -> 對應的 vowel 加 1
//       (3) 其他       -> 什麼都不用做
//    讀完之後，用 for 印出數字的次數 (只印有出現的)，母音五個都印。
// 三、程式逐段說明
//    while ((ch = getchar()) != '#')     先讀字元存進 ch，再和 # 比較；括號不能省，不然會先比較再指定
//    if (ch >= '0' && ch <= '9')         判斷範圍用 if，因為 switch 的 case 只能放單一個常數
//    digit[ch - '0']++;                  字元 '0' 是 48，'0' - '0' = 0，'5' - '0' = 5，剛好可以當索引
//    case 'a': case 'A':                 大小寫疊在一起，共用同一個 vowel[0]++
//    int digit[10] = { 0 };              陣列要歸零，不然次數會從亂數開始
//    if (digit[i] != 0)                  只印出現過的數字
// 四、手算追蹤 (輸入 Hi 2A#)
//         字元    走哪一條        結果
//         H       其他            不變
//         i       母音 i          vowel[2] = 1
//         空白    其他            不變
//         2       數字            digit[2] = 1
//         A       母音 a          vowel[0] = 1
//         #       結束            跳出迴圈
//       輸出：數字 2 出現 1 次；a:1 e:0 i:1 o:0 u:0
// 五、易錯點
//    1. 陣列沒有歸零，次數從亂數開始
//    2. 判斷數字寫成 ch >= 0 && ch <= 9，少了引號，比較的是 ASCII 碼 0 到 9，不是字元 '0' 到 '9'
//    3. case 後面漏掉 break，會掉到下一個母音
//    4. 輸入時換行字元也會被讀到，但它不是數字也不是母音，所以不影響結果
// 六、講課提醒
//    可以問同學：'a' 和 'A' 的 ASCII 碼差多少？(32)，如果不用 case 疊在一起，有沒有別的方法？(先轉成小寫再判斷)
