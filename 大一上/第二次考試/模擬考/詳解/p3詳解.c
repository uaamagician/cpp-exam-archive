// 程式設計一 第二次上機寫題，第三題 (4分)
//
//   猜數字
//      用亂數產生一個 1 到 20 的整數當作答案，玩家最多可以猜 5 次
//      每次猜測後，猜錯時印出「太大了」或「太小了」；猜對就立刻結束，不再繼續猜
//      結束後，猜對印出「恭喜你,第 N 次猜對了」，5 次都沒猜對則印出答案
//
//   提示：1. 使用 srand((unsigned)time(NULL)) 設定亂數種子，只設定一次，需要 #include <time.h>
//         2. rand() % 20 + 1 可以產生 1 到 20 的整數
//         3. 使用 while，條件同時判斷次數與旗標 flag，猜對時把 flag 設成 0，迴圈就會提早結束
//         4. 迴圈結束後的 i 已經多加了 1
//         輸出結果與下面的參考輸出相同即可 (亂數答案每次不同，下面假設答案是 13)。
//   變數要求
//      int 變數 ix 放答案，iz 放玩家猜的數，i 放目前是第幾次，flag 是旗標
// ---------------------------------------------------------------------------------------------
//   以下的輸出為本題輸出參考
//   第 1 次猜測(1~20): 10
//   太小了
//   第 2 次猜測(1~20): 15
//   太大了
//   第 3 次猜測(1~20): 13
//   恭喜你,第 3 次猜對了
//
//   (5 次都猜錯的情況)
//   機會用完了,答案是 13

#define P3
#ifdef P3

#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>
#include <time.h>

int main(void)
{
	int ix, iz, i, flag;

	srand((unsigned)time(NULL));
	ix = rand() % 20 + 1;
	i = 1;
	flag = 1;

	while (i <= 5 && flag == 1) {
		printf("第 %d 次猜測(1~20): ", i); scanf("%d", &iz);

		if (iz == ix) {
			flag = 0;
		}
		else if (iz > ix) {
			printf("太大了\n");
		}
		else {
			printf("太小了\n");
		}
		i++;
	}

	if (flag == 0) {
		printf("恭喜你,第 %d 次猜對了\n", i - 1);
	}
	else {
		printf("機會用完了,答案是 %d\n", ix);
	}

	system("pause"); return(0);
}

#endif

// =================================== 詳解 ===================================
// 1. 考點：rand 與 srand、while 配合旗標 flag 提早結束、if...else if...else
// 2. srand 只在程式開頭設定一次，rand() % 20 + 1 產生 1 到 20；srand 放進迴圈裡，每圈重設種子，結果會重複
// 3. flag = 1 代表還沒猜對，猜對時改成 0；while (i <= 5 && flag == 1) 同時控制次數與提早結束
// 4. 迴圈結束後 i 已經多加了 1，所以猜對的次數是 i - 1
// 5. 手算驗證 (答案 13)：第 1 次猜 10 太小了；第 2 次猜 15 太大了；第 3 次猜 13，flag = 0，i++ 之後 i = 4，印出 i - 1 = 3
// 6. 易錯點：猜對後沒有降 flag，程式會繼續要求猜測；用 i 直接印次數多算了 1；srand 放進迴圈
