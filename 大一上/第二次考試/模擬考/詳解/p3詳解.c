// 程式設計一 第二次上機寫題，第三題 (4分)
//
//   猜數字
//      用亂數產生一個 1 到 20 的整數當作答案，玩家最多可以猜 5 次
//      每次猜測後，猜錯時印出「太大了」或「太小了」；猜對就立刻結束，不再繼續猜
//      結束後，猜對印出「恭喜你,第 N 次猜對了」，5 次都沒猜對則印出答案
//
//   提示：1. 使用 srand((unsigned)time(NULL)) 設定亂數種子，只設定一次，需要 #include <time.h>
//         2. rand() % 20 + 1 可以產生 1 到 20 的整數
//         3. 使用 while，條件同時判斷次數與旗標 flag，猜對時把 flag 設成 0，迴圈就會提早結束
//         4. 迴圈結束後的 i 已經多加了 1
//         輸出結果與下面的參考輸出相同即可 (亂數答案每次不同，下面假設答案是 13)。
//   變數要求
//      int 變數 ix 放答案，iz 放玩家猜的數，i 放目前是第幾次，flag 是旗標
// ---------------------------------------------------------------------------------------------
//   以下的輸出為本題輸出參考
//   第 1 次猜測(1~20): 10
//   太小了
//   第 2 次猜測(1~20): 15
//   太大了
//   第 3 次猜測(1~20): 13
//   恭喜你,第 3 次猜對了
//
//   (5 次都猜錯的情況)
//   機會用完了,答案是 13

#define P3
#ifdef P3

#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>
#include <time.h>

int main(void)
{
	int ix, iz, i, flag;

	srand((unsigned)time(NULL));
	ix = rand() % 20 + 1;
	i = 1;
	flag = 1;

	while (i <= 5 && flag == 1) {
		printf("第 %d 次猜測(1~20): ", i); scanf("%d", &iz);

		if (iz == ix) {
			flag = 0;
		}
		else if (iz > ix) {
			printf("太大了\n");
		}
		else {
			printf("太小了\n");
		}
		i++;
	}

	if (flag == 0) {
		printf("恭喜你,第 %d 次猜對了\n", i - 1);
	}
	else {
		printf("機會用完了,答案是 %d\n", ix);
	}

	system("pause"); return(0);
}

#endif

// =================================== 詳解 ===================================
// 一、這題在考什麼
//    rand 與 srand、while 配合旗標 flag 提早結束、if...else if...else
// 二、解題思路
//    先用亂數產生答案。接著最多猜 5 次，所以 while 要同時管兩件事：次數還沒到 5，而且還沒猜對。
//    「還沒猜對」用 flag 表示：flag 是 1 代表還沒猜對，猜對時把它改成 0，迴圈就會停。
//    迴圈結束後有兩種可能：flag 是 0 (猜對了) 或 flag 還是 1 (5 次都用完)，再分別印結果。
// 三、程式逐段說明
//    srand((unsigned)time(NULL));    設定亂數種子，只做一次；不設的話每次執行答案都一樣
//    ix = rand() % 20 + 1;           rand() % 20 是 0 到 19，加 1 變成 1 到 20
//    while (i <= 5 && flag == 1)     兩個條件都成立才繼續猜
//    if (iz == ix) flag = 0;         猜對就降旗，其他兩個 else 印提示
//    i++;                            不管猜對猜錯，次數都要加 1
//    if (flag == 0) ... i - 1        迴圈結束時 i 已經多加了 1，所以猜對的次數是 i - 1
// 四、手算追蹤 (假設答案 13)
//         回合 i   猜的數    結果       flag    i++ 之後
//         1        10        太小了     1       2
//         2        15        太大了     1       3
//         3        13        猜對       0       4
//       迴圈結束 (flag 變成 0)，印出 i - 1 = 3，所以是「第 3 次猜對了」
//       如果 5 次都沒猜對：第 5 回合結束 i 變成 6，6 <= 5 不成立，迴圈結束，flag 還是 1，印出答案
// 五、易錯點
//    1. srand 放進迴圈裡，每一圈重設種子，結果會重複
//    2. 迴圈結束後直接印 i，多算了 1
//    3. 猜對後沒有把 flag 設成 0，程式還會繼續要求輸入
// 六、講課提醒
//    可以問同學：為什麼不能直接用 for (i = 1; i <= 5; i++)？(猜對後 for 不會自己停，要另外處理)
