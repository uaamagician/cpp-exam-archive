#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>

int main(void)
{
	int a, b, c, max, min, mid;
	int arr[5], i, t;

	printf("輸入三個整數: "); scanf("%d%d%d", &a, &b, &c);

	max = a;
	if (b > max) {
		max = b;
	}
	if (c > max) {
		max = c;
	}
	min = a;
	if (b < min) {
		min = b;
	}
	if (c < min) {
		min = c;
	}
	mid = a + b + c - max - min;
	printf("最大 %d 最小 %d 中間 %d\n", max, min, mid);

	printf("輸入 5 個整數: ");
	for (i = 0; i < 5; i++) {
		scanf("%d", &arr[i]);
	}

	for (i = 0; i < 4; i++) {
		if (arr[i] > arr[i + 1]) {
			t = arr[i];
			arr[i] = arr[i + 1];
			arr[i + 1] = t;
		}
	}

	for (i = 0; i < 5; i++) {
		printf("%d ", arr[i]);
	}
	printf("\n最大值 %d\n", arr[4]);

	system("pause"); return(0);
}

#endif

// =================================== 詳解 ===================================
// 一、這題在考什麼
//    if 比較、一維陣列、for 迴圈、兩個變數交換
// 二、解題思路
//    需求一：不需要排序。先假設 a 最大，拿 b 來挑戰 (b 比較大就取代)，再拿 c 來挑戰。最小值也是同樣的做法。
//            中間值不用再比：三個數的總和 - 最大 - 最小，剩下的就是中間值。
//    需求二：只做「一趟」相鄰比較。從最左邊開始，每次比 arr[i] 和 arr[i + 1]，左邊比較大就交換。
//            這樣最大的數會像泡泡一樣，一路被推到最右邊。
// 三、程式逐段說明
//    max = a; if (b > max) max = b; ...   先假設 a 最大，b、c 各挑戰一次，贏了就取代
//    mid = a + b + c - max - min;         總和扣掉最大與最小，剩下的就是中間值
//    for (i = 0; i < 5; i++) scanf        讀 5 個數進陣列，要寫 &arr[i]
//    for (i = 0; i < 4; i++)              為什麼是 4 不是 5？迴圈裡會用到 arr[i + 1]，i 最大是 3，arr[4] 才不會越界
//    t = arr[i]; arr[i] = arr[i+1]; ...   交換三步驟：先把 arr[i] 存進 t，不然被蓋掉就找不回來
// 四、手算追蹤
//    需求一 (輸入 7 3 9)：max 起始 7，c = 9 比較大，所以 max = 9；min 起始 7，b = 3 比較小，所以 min = 3
//                         mid = 7 + 3 + 9 - 9 - 3 = 7
//    需求二 (輸入 5 2 8 1 6)：
//         i    比較        動作     陣列
//         0    5 與 2      交換     2 5 8 1 6
//         1    5 與 8      不換     2 5 8 1 6
//         2    8 與 1      交換     2 5 1 8 6
//         3    8 與 6      交換     2 5 1 6 8
//       最大的 8 到了最後一格，但整個陣列還沒有排好 (2 5 1 6 8)
// 五、易錯點
//    1. 迴圈寫成 i < 5，會用到 arr[5]，超出陣列範圍
//    2. 交換沒有暫存變數，直接 arr[i] = arr[i+1]，原本的值就不見了
//    3. 以為一趟就排好了，其實只有最大值到定位
// 六、講課提醒
//    可以問同學：如果要完全排好，要做幾趟？(最多 4 趟，這題只出一趟)
