// 程式設計一 第二次上機寫題，第一題 (2+2分)
//
//   需求一：
//      輸入三個整數 a b c，輸出其中最大的、最小的與中間大小的數
//      (只能使用 if，不可以先排序)
//   需求二：
//      輸入 5 個整數存進一維陣列 arr
//      只用「一個」for 迴圈，從頭到尾比較相鄰的兩個數，前面的比後面的大就交換
//      做完後輸出陣列的內容與最大值
//
//   計分方式
//      1. 完成需求一，2 分
//      2. 完成需求二，2 分
//
//   提示：需求二這一趟做完後，最大的數會在陣列的最後一格
//         交換兩個變數的值需要第三個暫存變數
//         輸出結果與下面的參考輸出相同即可。
// ---------------------------------------------------------------------------------------------
//   以下的輸出為本題輸出參考
//   輸入三個整數: 7 3 9
//   最大 9 最小 3 中間 7
//   輸入 5 個整數: 5 2 8 1 6
//   2 5 1 6 8
//   最大值 8

#define P1
#ifdef P1

#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>

int main(void)
{
	int a, b, c, max, min, mid;
	int arr[5], i, t;

	printf("輸入三個整數: "); scanf("%d%d%d", &a, &b, &c);

	max = a;
	if (b > max) {
		max = b;
	}
	if (c > max) {
		max = c;
	}
	min = a;
	if (b < min) {
		min = b;
	}
	if (c < min) {
		min = c;
	}
	mid = a + b + c - max - min;
	printf("最大 %d 最小 %d 中間 %d\n", max, min, mid);

	printf("輸入 5 個整數: ");
	for (i = 0; i < 5; i++) {
		scanf("%d", &arr[i]);
	}

	for (i = 0; i < 4; i++) {
		if (arr[i] > arr[i + 1]) {
			t = arr[i];
			arr[i] = arr[i + 1];
			arr[i + 1] = t;
		}
	}

	for (i = 0; i < 5; i++) {
		printf("%d ", arr[i]);
	}
	printf("\n最大值 %d\n", arr[4]);

	system("pause"); return(0);
}

#endif

// =================================== 詳解 ===================================
// 1. 考點：if 比較、一維陣列、for 迴圈、兩變數交換
// 2. 需求一：先假設 a 最大，再拿 b、c 挑戰，最小值同理。中間值 = 總和 - 最大 - 最小，不用再比較
// 3. 需求二：「一趟」相鄰交換，i 只能到 3，因為要比較 arr[i] 與 arr[i+1]，i 到 4 會用到 arr[5]，超出陣列範圍
// 4. 交換需要暫存變數 t：t = arr[i]; arr[i] = arr[i+1]; arr[i+1] = t;
// 5. 手算驗證 (5 2 8 1 6)：
//      (5,2) 交換 -> 2 5 8 1 6
//      (5,8) 不換
//      (8,1) 交換 -> 2 5 1 8 6
//      (8,6) 交換 -> 2 5 1 6 8，最大的 8 到了最後一格
// 6. 易錯點：迴圈寫成 i < 5 造成越界；交換時沒有暫存變數把值蓋掉；以為一趟就排好了，其實只有最大值到定位
