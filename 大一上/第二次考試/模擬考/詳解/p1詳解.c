// 程式設計一 第二次上機寫題，第一題 (2+2分)
//
//   需求一：
//      輸入三個整數 a b c，輸出其中最大的、最小的與中間大小的數
//      (只能使用 if，不可以先排序)
//   需求二：
//      輸入 5 個整數存進一維陣列 arr
//      只用「一個」for 迴圈，從頭到尾比較相鄰的兩個數，前面的比後面的大就交換
//      做完後輸出陣列的內容與最大值
//
//   計分方式
//      1. 完成需求一，2 分
//      2. 完成需求二，2 分
//
//   提示：需求二這一趟做完後，最大的數會在陣列的最後一格
//         交換兩個變數的值需要第三個暫存變數
//         輸出結果與下面的參考輸出相同即可。
//   變數要求
//      int 變數 a、b、c 放輸入的三個數，max、min、mid 放最大、最小、中間值
//      int 陣列 arr，5 個元素
//      int 變數 t，交換時暫存用
//      迴圈用的變數請自己宣告，名稱使用 i
// ---------------------------------------------------------------------------------------------
//   以下的輸出為本題輸出參考
//   輸入三個整數: 7 3 9
//   最大 9 最小 3 中間 7
//   輸入 5 個整數: 5 2 8 1 6
//   2 5 1 6 8
//   最大值 8

