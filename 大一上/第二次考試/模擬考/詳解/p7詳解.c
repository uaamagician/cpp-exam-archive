#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

int main(void)
{
	char str[20];
	int i, j, k, len;

	do {
		printf("輸入一個字串: "); scanf("%s", str);
		len = strlen(str);
		if (len > 1) {
			printf("反向: ");
			for (i = len - 1; i >= 0; i--) {
				putchar(str[i]);
			}
			printf("\n");

			i = 0;
			j = len - 1;
			while (i < j && str[i] == str[j]) {
				i++;
				j--;
			}

			if (i >= j) {
				printf("完全回文\n");
			}
			else {
				for (k = 0; k <= j - i; k++) {
					str[k] = str[i + k];
				}
				str[j - i + 1] = '\0';
				printf("剩下: %s\n", str);
			}
		}
	} while (len > 1);

	system("pause"); return(0);
}

#endif

// =================================== 詳解 ===================================
// 一、這題在考什麼
//    字元陣列與字串、strlen、do...while、while 配合 && 提早結束、陣列元素搬移
// 二、解題思路
//    重複輸入字串，長度是 1 就結束。每次輸入要做兩件事：
//    (1) 反向輸出：從最後一個字元倒著印。
//    (2) 從頭尾往中間縮：i 指頭、j 指尾，兩邊字元相同就一起往中間走，遇到第一組不同就停。
//        停下來之後，str[i] 到 str[j] 就是剩下的中間部分；如果 i 和 j 走到交會 (i >= j)，代表整個字串都對稱。
//    剩下的部分要印出來，做法是整段往前搬到 str 開頭，再補一個 '\0' 當結尾。
// 三、程式逐段說明
//    len = strlen(str);                       字串長度，不含最後的 '\0'
//    for (i = len - 1; i >= 0; i--)           索引最大是 len - 1，所以從這裡倒著印
//    while (i < j && str[i] == str[j])        i < j 是「還沒交會」，兩個條件都成立才繼續縮
//    if (i >= j)                              交會了還都相同，代表完全回文
//    str[k] = str[i + k];                     把剩下的部分整段往前搬 i 格，k 到 j - i 為止 (長度是 j - i + 1)
//    str[j - i + 1] = '\0';                   搬完要補結尾，不然後面會留著舊字元
//    } while (len > 1);                       長度只有 1 才結束
// 四、手算追蹤
//    abcxyzcba (長度 9)：
//         i    j    str[i]  str[j]    動作
//         0    8    a       a         相同，i = 1, j = 7
//         1    7    b       b         相同，i = 2, j = 6
//         2    6    c       c         相同，i = 3, j = 5
//         3    5    x       z         不同，停止
//       剩下 str[3] 到 str[5] = xyz，長度 j - i + 1 = 3；搬移 str[0] = str[3]、str[1] = str[4]、str[2] = str[5]，str[3] = '\0'
//    level (長度 5)：i = 0, j = 4：l = l；i = 1, j = 3：e = e；i = 2, j = 2：i < j 不成立，停止。i >= j，印完全回文
//    abba (長度 4)：i = 0, j = 3：a = a；i = 1, j = 2：b = b；i = 2, j = 1：交會，停止。i >= j，印完全回文
//    hello：i = 0, j = 4：h 不等於 o，直接停止，i = 0，剩下整個字串 hello
// 五、易錯點
//    1. 先搬移字串再印反向，反向就不是原本的字串了 (順序要先反向後剝除)
//    2. 搬移後忘了補 '\0'，後面會留著舊字元
//    3. 把 i >= j 寫成 i > j，abba 這種偶數長度的回文會判錯
//    4. scanf 的 %s 前面不加 &，因為字串名稱本身就是位址
// 六、講課提醒
//    可以問同學：為什麼奇數長度的回文最後 i 會等於 j？(因為中間那個字元，自己對自己一定相同，這時 i < j 已經不成立)
