#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>

int main(void)
{
	int n, i, sign;
	float tot, diff;

	do {
		printf("輸入 n(1~20): "); scanf("%d", &n);
	} while (n < 1 || n > 20);

	tot = 0;
	sign = 1;
	for (i = 1; i <= n; i++) {
		tot = tot + sign / (float)(2 * i - 1);
		sign = sign * -1;
	}
	printf("前 %d 項: %f\n", n, 4 * tot);

	tot = 0;
	sign = 1;
	i = 0;
	diff = 1;
	while (diff >= 0.01) {
		i++;
		tot = tot + sign / (float)(2 * i - 1);
		sign = sign * -1;
		diff = 4 * tot - 3.14159f;
		if (diff < 0) {
			diff = -diff;
		}
	}
	printf("至少要 %d 項: %f\n", i, 4 * tot);

	system("pause"); return(0);
}

#endif

// =================================== 詳解 ===================================
// 1. 考點：do...while 輸入檢查、for 累加、while、型別轉換、正負號交替
// 2. do...while 先做一次再判斷，條件寫「不合法」的情況：n < 1 || n > 20
// 3. 第 i 項的分母 2*i - 1 是 int，sign / (2*i - 1) 會做整數除法 (1/3 = 0)，所以要 (float)(2 * i - 1)
// 4. sign 每圈乘 -1，就能正負交替
// 5. 需求二不知道要幾項，用 while；條件是 diff >= 0.01，diff 是負數時要自己變成正的，跳出迴圈時 i 剛好是項數 (100)
// 6. 手算驗證 (n = 4)：1 - 0.3333 + 0.2 - 0.1429 = 0.7238，乘 4 = 2.8952
// 7. 易錯點：沒有轉型整個級數只剩第一項；diff 沒取絕對值，級數和小於 3.14159 時 diff 是負的，while 一開始就跳出；忘了乘 4
