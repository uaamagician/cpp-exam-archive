// 程式設計一 第二次上機寫題，第四題 (3+3分)
//
//   需求一：
//      輸入 n (1 到 20 的整數，輸入不合法就重新輸入)
//      計算下面級數的前 n 項和，再乘以 4，輸出結果
//          1 - 1/3 + 1/5 - 1/7 + 1/9 - ...
//   需求二：
//      同樣的級數，用 while 找出「至少要加到第幾項」
//      才會使 (級數和 x 4) 與 3.14159 的差距小於 0.01
//      輸出項數與當時的結果 (不使用 math.h，差距的正負請自己處理)
//
//   計分方式
//      1. 完成需求一，3 分
//      2. 完成需求二，3 分
//
//   提示：第 i 項的分母是 2*i - 1，正負號每一項交替，可以用一個變數 sign 每次乘以 -1
//         分母是 int，sign / (2*i - 1) 會變成整數除法，要把分母轉型成 (float)
//         輸出結果與下面的參考輸出相同即可。
//   變數要求
//      int 變數 n、sign (正負號)，起始值自己設定
//      float 變數 tot (級數和)、diff (差距)
//      i 是項數的計數變數，請自己宣告
//   流程提示 (n = 3 為例)
//      i = 1 : sign = 1，加上 1 / 1   -> tot = 1，sign 變 -1
//      i = 2 : sign = -1，加上 -1 / 3 -> tot = 0.6667，sign 變 1
//      i = 3 : sign = 1，加上 1 / 5   -> tot = 0.8667，輸出 4 * tot = 3.466667
//      需求二：每加一項就重新算 diff，diff 小於 0.01 的那一刻 i 就是答案
// ---------------------------------------------------------------------------------------------
//   以下的輸出為本題輸出參考
//   輸入 n(1~20): 25
//   輸入 n(1~20): 4
//   前 4 項: 2.895238
//   至少要 100 項: 3.131593

