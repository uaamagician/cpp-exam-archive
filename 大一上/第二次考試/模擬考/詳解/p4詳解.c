#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>

int main(void)
{
	int n, i, sign;
	float tot, diff;

	do {
		printf("輸入 n(1~20): "); scanf("%d", &n);
	} while (n < 1 || n > 20);

	tot = 0;
	sign = 1;
	for (i = 1; i <= n; i++) {
		tot = tot + sign / (float)(2 * i - 1);
		sign = sign * -1;
	}
	printf("前 %d 項: %f\n", n, 4 * tot);

	tot = 0;
	sign = 1;
	i = 0;
	diff = 1;
	while (diff >= 0.01) {
		i++;
		tot = tot + sign / (float)(2 * i - 1);
		sign = sign * -1;
		diff = 4 * tot - 3.14159f;
		if (diff < 0) {
			diff = -diff;
		}
	}
	printf("至少要 %d 項: %f\n", i, 4 * tot);

	system("pause"); return(0);
}

#endif

// =================================== 詳解 ===================================
// 一、這題在考什麼
//    do...while 輸入檢查、for 累加、while、型別轉換、用 sign 讓正負號交替
// 二、解題思路
//    需求一：先用 do...while 確保 n 在 1 到 20。再用 for 把前 n 項加起來。
//            第 i 項是 1 / (2*i - 1)：分母依序是 1、3、5、7...；正負號交替，用 sign 每次乘 -1。
//    需求二：這次不知道要加幾項，所以用 while。每加一項就檢查「4 * 級數和」離 3.14159 夠不夠近 (差距小於 0.01)。
//            差距可能是正也可能是負，所以負的要先變成正的。跳出迴圈時，i 剛好就是項數。
// 三、程式逐段說明
//    } while (n < 1 || n > 20);          do...while 的條件寫「不合法」的情況，不合法就重來
//    sign / (float)(2 * i - 1)           分母是 int，int 除 int 會變成整數除法 (1/3 是 0)，所以分母要轉成 float
//    sign = sign * -1;                   1 變 -1，-1 變 1，正負號交替
//    printf(..., 4 * tot)                級數和乘 4 才接近圓周率
//    while (diff >= 0.01)                差距還沒小於 0.01 就繼續加下一項
//    if (diff < 0) diff = -diff;         手動取絕對值，不使用 math.h
// 四、手算追蹤 (n = 4)
//         i    sign    分母    這一項     tot
//         1     1       1      +1         1.0000
//         2    -1       3      -0.3333    0.6667
//         3     1       5      +0.2       0.8667
//         4    -1       7      -0.1429    0.7238
//       4 * 0.7238 = 2.8952，所以輸出 2.895238
//       需求二：項數越多，4 * tot 會在 3.14159 的上下來回震盪，越來越靠近；加到第 100 項時 diff 第一次小於 0.01
// 五、易錯點
//    1. 分母沒轉型，整個級數只剩第一項 (後面 1/3、1/5 都變 0)
//    2. diff 沒有取絕對值，級數和小於 3.14159 時 diff 是負的，while 一開始就跳出
//    3. 忘了乘 4
//    4. 需求二忘了重設 tot、sign、i，接續需求一的值繼續算
// 六、講課提醒
//    可以問同學：為什麼 sign 不直接寫成 float？(可以，但這裡用 int 配合分母轉型，兩種都行)
