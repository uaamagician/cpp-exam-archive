#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>
#include <math.h>
int main(void)
{
	int a, b, c;
	float x, y, z;
	int t;
	float ft;

	printf("輸入 a b c 三個整數中間以空格為間隔 "); scanf("%d%d%d", &a, &b, &c);
	printf("輸入 x y 兩個浮點數中間以空格為間隔 "); scanf("%f%f", &x, &y);
	printf("\n------- Part 1 -------\n");
	z = (a*x*x - b*y) / (c*x + a*y*y - b);

	printf("(a*x^2 - b*y)/(c*x + a*y^2 - b) = %8.5f\n", z);

	printf("\n------- Part 2 -------\n");
	t = b;  b = c;  c = t;
	ft = x; x = y;  y = ft;
	z = x*x*x + a*x*y*y - b*x*x*y + c*y*y*y;

	printf("x^3 + a*x*y^2 - b*x^2*y + c*y^3 = %8.5f\n", z);

	system("pause"); return(0);
}

#endif

// =================================== 詳解 ===================================
// 1. 考點：變數宣告、scanf 格式 (%d 整數、%f 浮點數)、運算式寫法、交換兩個變數
// 2. scanf 的格式不能寫成 "%%%"：%% 是「印出百分號」，要寫 "%d%d%d" 與 "%f%f"，而且每個變數前面要加 &
// 3. 不能用 pow，次方用連乘：x^2 = x*x、y^2 = y*y、x^3 = x*x*x
// 4. 交換三步驟：t = b; b = c; c = t;（不能只寫 b = c; c = b;，那樣兩個都會變成 c）
//    整數與浮點數要各用各的暫存變數：t 是 int、ft 是 float
// 5. Part 2 是「互換之後」才計算：b c x y 已經是交換後的值，a 沒有換
// 6. 手算驗證 Part 1：a=3 b=-2 c=1 x=1.5 y=2.0
//      分子 = 3*2.25 - (-2)*2 = 6.75 + 4 = 10.75
//      分母 = 1*1.5 + 3*4 - (-2) = 1.5 + 12 + 2 = 15.5
//      z = 10.75 / 15.5 = 0.69355
//    手算驗證 Part 2：交換後 b=1 c=-2 x=2.0 y=1.5
//      x^3 = 8，a*x*y^2 = 3*2*2.25 = 13.5，b*x^2*y = 1*4*1.5 = 6，c*y^3 = -2*3.375 = -6.75
//      8 + 13.5 - 6 - 6.75 = 8.75
// 7. 易錯點：分母沒加括號會變成先除再加減；減去負數時正負號要小心（b 是 -2，-b*y 會變成加）
