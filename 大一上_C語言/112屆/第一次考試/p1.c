//			條件2：紅茶買超過(含) 35 杯數或咖啡購買超過 20 杯
// 			同時滿足條件1 與 條件2 時售價打 85 折，且紅茶買 2 送 1、咖啡買 3 送 1
//          沒有滿足打折條件時，紅茶與咖啡都是買 4 送 1
//			輸出應付的原價與打折後的總價以及各應給的杯數與總杯數
// 
//	 計分方式
//		1. 完成需求 1 , 1 分
//      2. 紅茶與咖啡售價以 #define 宣告為常數符號，且完成需求1的輸出， 1 分
//		3. 完成需求 2 , 2 分
// 
//   提示：需使用 if...else，將兩個需求的程式碼各複製一份到對應的 printf 函式後面即可連續輸入兩次
//		   需求 1 兩次輸入分別為 15 15 以及 20 20
//		   需求 2 兩次輸入分別為 30 20 以及 40 20
//         輸出結果與下面的參考輸出相同即可。
// ---------------------------------------------------------------------------------------------
//   以下的輸出為本題輸出參考
//	------------需求 1 ------------
// 	依序輸入紅茶與咖啡的購買杯數 : 15 15
//  未達打折條件，總價為 : 1350
//	依序輸入紅茶與咖啡的購買杯數 : 20 20
//	總價為 : 1800 打折後是 1620
//	
// 	------------需求 2 ------------
// 	依序輸入紅茶與咖啡的購買杯數: 30 20
//  未達打折條件，總價為 : 2100
//	紅茶原購買 : 30 杯, 咖啡原購買 : 20 杯
//	紅茶應製作 : 37 杯, 咖啡應製作 : 25 杯
//	
// 	依序輸入紅茶與咖啡的購買杯數 : 40 20
//  總價為 : 2400 打折後是 2040
//	紅茶原購買 : 40 杯, 咖啡原購買 : 20 杯
//	紅茶應製作 : 60 杯, 咖啡應製作 : 26 杯
//	

