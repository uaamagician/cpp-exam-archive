#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>
	
#define TEA 30			// 宣告紅茶(TEA)售價的常數
#define COFFEE TEA * 2	// 宣告咖啡(COFFEE)售價的常數

int main(void)
{
	int tea, coffee, tp, tc;	// 宣告紅茶、咖啡購買的杯數、總價與總杯數等相關變數
	int tp2, tea2, coffee2;	// 宣告打折後的總價、紅茶製作的杯數、咖啡製作的杯數等相關變數
	
	printf("------------  需求 1 ------------\n");
	printf("依序輸入紅茶與咖啡的購買杯數 : "); scanf("%d%d", &tea, &coffee);

	tp = tea * TEA + coffee * COFFEE;
	tc = tea + coffee;

	if (tp >= 1400 && tc > 30) {	// 當總價超過(含) 1400 時且總杯數超過 30 杯時售價打 9 折
		tp2 = tp * 0.9;
		printf("總價為: %d 打折後是 %d \n", tp, tp2);
	}
	else {
		printf("未達打折條件，總價為: %d \n", tp);
	}
	rewind(stdin);
	// 以下複製貼需求一寫好的程式碼到這裡，就不用執行兩次了
	printf("依序輸入紅茶與咖啡的購買杯數 : "); scanf("%d%d", &tea, &coffee);

	tp = tea * TEA + coffee * COFFEE;
	tc = tea + coffee;

	if (tp >= 1400 && tc > 30) {	// 當總價超過(含) 1400 時且總杯數超過 30 杯時售價打 9 折
		tp2 = tp * 0.9;
		printf("總價為: %d 打折後是 %d \n", tp, tp2);
	}
	else {
		printf("未達打折條件，總價為: %d \n", tp);
	}




	printf("\n------------  需求 2 ------------\n");
	printf("依序輸入紅茶與咖啡的購買杯數 : "); scanf("%d%d", &tea, &coffee);

	// 條件1：總杯數超過(含) 50 杯。
	// 條件2：紅茶買超過(含) 35 杯數或咖啡購買超過 20 杯
	// 打折條件為條件1 與 條件2 同時成立，則售價打 85 折 

	tp = tea * TEA + coffee * COFFEE;
	tc = tea + coffee;

	if (tc >= 50 && ((tea >= 35) ||(coffee > 20))) {
		// 當滿足打折條件時，紅茶買 2 送 1、咖啡買 3 送 1
		tp2 = tp * 0.85;
		tea2 = tea + tea / 2;
		coffee2 = coffee + coffee / 3;
		printf("總價為: %d 打折後是 %d \n", tp, tp2);

	}
	else {
		// 當沒有滿足打折條件時，紅茶與咖啡都是買 4 送 1
		tea2 = tea + tea / 4;
		coffee2 = coffee + coffee / 4;
		printf("未達打折條件，總價為: %d \n", tp);
	}

	printf("紅茶原購買: %2d 杯, 咖啡原購買: %2d 杯\n", tea, coffee);
	printf("紅茶應製作: %2d 杯, 咖啡應製作: %2d 杯\n\n", tea2, coffee2);

	rewind(stdin);
	// 以下複製貼需求二寫好的程式碼到這裡，就不用執行兩次了
	printf("依序輸入紅茶與咖啡的購買杯數 : "); scanf("%d%d", &tea, &coffee);

	// 條件1：總杯數超過(含) 50 杯。
	// 條件2：紅茶買超過(含) 35 杯數或咖啡購買超過 20 杯
	// 打折條件為條件1 與 條件2 同時成立，則售價打 85 折 

	tp = tea * TEA + coffee * COFFEE;
	tc = tea + coffee;

	if (tc >= 50 && ((tea >= 35) || (coffee > 20))) {
		// 當滿足打折條件時，紅茶買 2 送 1、咖啡買 3 送 1
		tp2 = tp * 0.85;
		tea2 = tea + tea / 2;
		coffee2 = coffee + coffee / 3;
		printf("總價為: %d 打折後是 %d \n", tp, tp2);

	}
	else {
		// 當沒有滿足打折條件時，紅茶與咖啡都是買 4 送 1
		tea2 = tea + tea / 4;
		coffee2 = coffee + coffee / 4;
		printf("未達打折條件，總價為: %d \n", tp);
	}

	printf("紅茶原購買: %2d 杯, 咖啡原購買: %2d 杯\n", tea, coffee);
	printf("紅茶應製作: %2d 杯, 咖啡應製作: %2d 杯\n\n", tea2, coffee2);



	system("pause"); return(0);
}

