//  設計一個時間換算的程式，讓使用者輸入總秒數，
//  換算成幾天、幾小時、幾分鐘、幾秒（1 天 = 86400 秒、1 小時 = 3600 秒、1 分鐘 = 60 秒），
//  而且輸出時必須由大而小依序顯示。 (3 分)
//
//  接著假設這個時間是從「星期一 00:00:00」開始算起，輸出經過這些秒數之後
//  現在是星期幾、上午或下午，以及 12 小時制的時間。 (3 分)
//    1. 星期幾：天數除以 7 取餘數，餘 0 是星期一，餘 1 是星期二，……，餘 6 是星期日
//    2. 小時數小於 12 是上午，否則是下午
//    3. 12 小時制：小時數除以 12 取餘數，如果餘數是 0，要顯示成 12
//    （例如 0 時顯示上午 12 時，12 時顯示下午 12 時，18 時顯示下午 6 時）
//
//  要求：星期幾必須使用 if...else if...else 完成
//
// 參考以下的輸出結果
//
// 請輸入總秒數: 100000
// 可換算:   1 天
//           3 時
//          46 分
//          40 秒
// 從星期一 00:00:00 開始算起，現在是 星期二 上午 3 時 46 分 40 秒
//
// 請輸入總秒數: 500000
// 可換算:   5 天
//          18 時
//          53 分
//          20 秒
// 從星期一 00:00:00 開始算起，現在是 星期六 下午 6 時 53 分 20 秒
//
// 請輸入總秒數: 259200
// 可換算:   3 天
//           0 時
//           0 分
//           0 秒
// 從星期一 00:00:00 開始算起，現在是 星期四 上午 12 時 0 分 0 秒
//

#define P5
#ifdef P5

#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>
int main(void)
{
	int total, day, hour, min, sec, w, h12;

	printf("請輸入總秒數: "); 	scanf("%d", &total);
	day = total / 86400;
	hour = (total % 86400) / 3600;
	min = ((total % 86400) % 3600) / 60;
	sec = (((total % 86400) % 3600) % 60);

	printf("可換算: %3d 天\n        %3d 時\n", day, hour);
	printf("        %3d 分\n        %3d 秒\n", min, sec);

	w = day % 7;
	printf("從星期一 00:00:00 開始算起，現在是 ");
	if (w == 0) {
		printf("星期一 ");
	}
	else if (w == 1) {
		printf("星期二 ");
	}
	else if (w == 2) {
		printf("星期三 ");
	}
	else if (w == 3) {
		printf("星期四 ");
	}
	else if (w == 4) {
		printf("星期五 ");
	}
	else if (w == 5) {
		printf("星期六 ");
	}
	else {
		printf("星期日 ");
	}

	if (hour < 12) {
		printf("上午 ");
	}
	else {
		printf("下午 ");
	}

	h12 = hour % 12;
	if (h12 == 0) {
		h12 = 12;
	}
	printf("%d 時 %d 分 %d 秒\n", h12, min, sec);

	system("pause");
	return 0;
}

#endif

// =================================== 詳解 ===================================
// 1. 考點：/ 與 % 的連續使用（跟兌換零錢同一套做法）、多重 if...else if...else
// 2. 換算：天 = total / 86400，之後每一層都先用 % 取出剩下的秒數，再除以下一個單位
//      hour = (total % 86400) / 3600
//      min  = ((total % 86400) % 3600) / 60
//      sec  = ((total % 86400) % 3600) % 60
// 3. 星期幾：w = day % 7，天數超過一週會繞回去，w 是 0 到 6，對應星期一到星期日
// 4. 上午／下午：hour < 12 是上午，否則是下午
// 5. 12 小時制：h12 = hour % 12；餘數是 0 時要改成 12（0 時是上午 12 時，12 時是下午 12 時）
// 6. 手算驗證：
//      100000：100000 / 86400 = 1 餘 13600；13600 / 3600 = 3 餘 2800；2800 / 60 = 46 餘 40
//              day = 1 -> 星期二；hour = 3 < 12 -> 上午；3 % 12 = 3
//      500000：5 天 18 時 53 分 20 秒；5 % 7 = 5 -> 星期六；18 >= 12 -> 下午；18 % 12 = 6
//      259200：3 天整，hour = 0；3 -> 星期四；0 < 12 -> 上午；0 % 12 = 0 -> 改成 12
// 7. 易錯點：星期的餘數對應寫錯一天；漏掉 h12 == 0 要改成 12；
//    printf 輸出格式 %3d 讓數字右對齊
