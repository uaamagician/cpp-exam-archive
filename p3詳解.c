// 程式設計一 第一次上機寫題，第三題 (4分)
//
// 輸出 20 到 120 間所有數的總和，以及所有偶數的和、所有奇數的和與所有 5 的倍數的和
//
// 參考以下的輸出結果
//
// 20+...+120 = 7070
// 奇數和 = 3500
// 偶數和 = 3570
// 5 的倍數和 = 1470
//

#define P3
#ifdef P3

#define _CRT_SECURE_NO_WARNINGS 1
#include <stdio.h>
#include <stdlib.h>

int main(void)
{
	int i, sumOdd, sumEven, sumFive, sumAll;
	i = 20; sumOdd = sumEven = sumFive = sumAll = 0;

	while (i <= 120) {
		if (i % 2 == 1) {
			sumOdd += i;
		}
		else {
			sumEven += i;
		}
		if (i % 5 == 0) {
			sumFive += i;
		}
		sumAll += i;
		i++;
	}

	printf("20+...+120 = %d\n奇數和 = %d\n偶數和 = %d\n5 的倍數和 = %d\n\n", sumAll, sumOdd, sumEven, sumFive);

	system("pause"); return(0);
}

#endif

// =================================== 詳解 ===================================
// 1. 考點：while 迴圈、% 取餘數、if...else、累加
// 2. 累加用的變數一定要先設成 0，迴圈變數 i 起始值是 20，結束條件 i <= 120
// 3. 奇偶是二選一，用 if...else：i % 2 == 1 是奇數，否則是偶數
// 4. 5 的倍數與奇偶無關，要「另外寫一個獨立的 if」；不能把它寫成 else if，否則 5 的倍數會被漏算
// 5. 全部的總和不管是哪一種都要加，放在 if 外面
// 6. 手算驗證：
//      全部：(20 + 120) * 101 / 2 = 7070
//      奇數：21, 23, ..., 119，共 50 個，(21 + 119) * 50 / 2 = 3500
//      偶數：20, 22, ..., 120，共 51 個，(20 + 120) * 51 / 2 = 3570，且 3500 + 3570 = 7070
//      5 的倍數：20, 25, ..., 120，共 21 個，(20 + 120) * 21 / 2 = 1470
// 7. 易錯點：忘了 i++ 變成無窮迴圈；範圍寫成 i < 120 少算 120；總和變數沒歸零
